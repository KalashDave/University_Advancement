def apply_dark_theme(fig, height=270):
    """
    Standardizes Plotly figures with the executive high-contrast dark palette.

    Parameters:
    -----------
    fig : plotly.graph_objects.Figure
        The Plotly chart figure to style.
    height : int, default=270
        Standardized height in pixels ensuring uniform 2x2 grid alignment.

    Returns:
    --------
    plotly.graph_objects.Figure
        Stylized figure with transparent background, Inter font typography,
        subtle slate gridlines (#334155), and crisp dark hover tooltips.
    """
    fig.update_layout(
        font=dict(family="Inter, -apple-system, sans-serif", size=11.5, color="#CBD5E1"),
        plot_bgcolor="rgba(0,0,0,0)",
        paper_bgcolor="rgba(0,0,0,0)",
        height=height,
        margin=dict(l=35, r=20, t=20, b=30),
        hovermode="closest",
        hoverlabel=dict(
            bgcolor="#020617",
            font_size=11.5,
            font_color="#FFFFFF",
            font_family="Inter, sans-serif",
            bordercolor="#475569"
        )
    )
    # Subtle slate gridlines with suppressed zero line for maximum data readability
    fig.update_xaxes(showgrid=True, gridcolor="#334155", tickfont=dict(size=10.5, color="#94A3B8"), zeroline=False)
    fig.update_yaxes(showgrid=True, gridcolor="#334155", tickfont=dict(size=10.5, color="#94A3B8"), zeroline=False)
    return fig


def format_tooltip(description: str, calculation: str, benchmark: str = None) -> str:
    """
    Constructs a standardized, multi-line executive tooltip for st.metric cards.

    Parameters:
    -----------
    description : str
        Plain English explanation of what the metric measures and why it matters.
    calculation : str
        Mathematical formula and CRM field references used to compute the value.
    benchmark : str, optional
        Relevant CASE, higher education, or institutional strategic target.

    Returns:
    --------
    str
        Formatted string containing Definition, Calculation, and Benchmark sections.
    """
    lines = [
        f"📌 Definition: {description}",
        f"📐 Calculation: {calculation}"
    ]
    if benchmark:
        lines.append(f"🎯 Target / Benchmark: {benchmark}")
    return "\n\n".join(lines)


