@st.cache_data(show_spinner=False)
def load_and_preprocess_advancement_data():
    """
    Ingests and transforms the raw constituent dataset for real-time dashboard analytics.

    Caching Strategy:
    -----------------
    Uses `@st.cache_data(show_spinner=False)` to memoize the loaded and enriched DataFrame.
    Streamlit computes this once on startup and serves it instantly to all subsequent user
    filter interactions without touching the disk or recomputing derived features.

    Data Transformations & Feature Engineering:
    -------------------------------------------
    1. Graduation Cohorts:
       - Young Alumni (<10 yrs): Class Year 2017 to 2025
       - Mid-Career (10-25 yrs): Class Year 2001 to 2016
       - Senior Alumni (25+ yrs): Class Year <= 2000
    2. Demographic Generations (based on Birth Year):
       - Silent Generation (<=1945), Baby Boomers (1946-1964), Gen X (1965-1980),
         Millennials (1981-1996), Gen Z (1997+)
    3. Geographic Groupings:
       - Segments geography into Quebec (primary local alumni hub), Rest of Canada,
         United States, and International regions.
    4. Philanthropic Indicators:
       - Binary donor flags for FY24, FY25, and FY26 (`Donated_FYxx`).
       - Historical giving flag (`Gave_Prior`) to identify lapsed vs first-time prospects.
    5. CASE AEM 4-Pillar Engagement Flags:
       - Philanthropic: Donated in FY26
       - Experiential: Attended >=1 university event in FY26
       - Volunteer: Active volunteer or advisory board member in FY26
       - Communication: Opened marketing emails or logged into McDill Connect
       - Pillar Count: Breadth score (0 to 4) reflecting constituent engagement depth.
    6. Display Aliasing:
       - Normalizes internal system codes into clean, executive-ready labels.

    Returns:
    --------
    pd.DataFrame
        Enriched DataFrame with 30,000 constituent records and downstream analytical features.
    """
    csv_path = "mcgill_advancement_raw_crm.csv"
    if not os.path.exists(csv_path):
        st.error(f"CRM extract file '{csv_path}' not found in workspace.")
        st.stop()
        
    df = pd.read_csv(csv_path)
    
    # 1. Graduation Cohort Segmentation
    df['Years_Since_Grad'] = 2026 - df['Class_Year']
    conditions_cohort = [
        (df['Class_Year'] >= 2017),
        (df['Class_Year'] >= 2001) & (df['Class_Year'] <= 2016),
        (df['Class_Year'] <= 2000)
    ]
    choices_cohort = [
        'Young Alumni (<10 yrs)',
        'Mid-Career (10-25 yrs)',
        'Senior Alumni (25+ yrs)'
    ]
    df['Graduation_Cohort'] = np.select(conditions_cohort, choices_cohort, default='Other')
    
    # 2. Demographic Generations (Birth Year Bins)
    gen_conditions = [
        (df['Birth_Year'] <= 1945),
        (df['Birth_Year'] >= 1946) & (df['Birth_Year'] <= 1964),
        (df['Birth_Year'] >= 1965) & (df['Birth_Year'] <= 1980),
        (df['Birth_Year'] >= 1981) & (df['Birth_Year'] <= 1996),
        (df['Birth_Year'] >= 1997)
    ]
    gen_choices = [
        'Silent (<=1945)',
        'Boomers (1946-64)',
        'Gen X (1965-80)',
        'Millennials (1981-96)',
        'Gen Z (1997+)'
    ]
    df['Generation'] = np.select(gen_conditions, gen_choices, default='Other')
    
    # 3. Gender Label Normalization
    gender_map = {'F': 'Female', 'M': 'Male', 'X': 'Non-Binary / Other'}
    df['Gender_Label'] = df['Gender'].map(gender_map).fillna('Other')
    
    # 4. Regional Geographic Categorization
    conditions_region = [
        (df['Province_State'] == 'QC'),
        (df['Country_of_Residence'] == 'Canada') & (df['Province_State'] != 'QC'),
        (df['Country_of_Residence'] == 'United States')
    ]
    choices_region = ['Quebec', 'Rest of Canada', 'United States']
    df['Geographic_Region'] = np.select(conditions_region, choices_region, default='International')
    
    # 5. Multi-Year Philanthropic Flags
    df['Donated_FY24'] = (df['Gift_Count_FY24'] > 0).astype(int)
    df['Donated_FY25'] = (df['Gift_Count_FY25'] > 0).astype(int)
    df['Donated_FY26'] = (df['Gift_Count_FY26'] > 0).astype(int)
    df['Gave_Prior'] = ((df['Lifetime_Gift_Count_Prior_To_FY24'] > 0) | (df['Donated_FY24'] == 1)).astype(int)
    
    # 6. CASE Alumni Engagement Metrics (AEM) 4 Pillars
    df['CASE_Philanthropic'] = df['Donated_FY26']
    df['CASE_Experiential'] = (df['Events_Attended_FY26'] > 0).astype(int)
    df['CASE_Volunteer'] = (df['Is_Active_Volunteer_FY26'] == 1).astype(int)
    df['CASE_Communication'] = ((df['Emails_Opened_FY26'] > 0) | (df['McGill_Connect_Logins_FY26'] > 0)).astype(int)
    df['CASE_Pillar_Count'] = (df['CASE_Philanthropic'] + df['CASE_Experiential'] + df['CASE_Volunteer'] + df['CASE_Communication'])
    
    # 7. Channel & Fund Designation Formatting (Executive Branding)
    df['Display_Channel'] = df['Primary_Solicitation_Channel_FY26'].replace({
        'Crowdfunding_McGill24': 'Crowdfunding_McDill24',
        'Email_Digital': 'Digital Solicitation',
        'Direct_Mail_Letter': 'Direct Mail Letter',
        'Phonathon_Student_Caller': 'Student Phonathon',
        'No_Solicitation': 'No Direct Solicitation'
    })
    
    df['Last_Gift_Designation'] = df['Last_Gift_Designation'].replace({
        'The McGill Fund (Unrestricted)': 'The McDill Fund (Unrestricted)',
        'Varsity Athletics & Martlets/Redbirds': 'Varsity Athletics & Recreation'
    })
    
    return df



df_master = load_and_preprocess_advancement_data()


